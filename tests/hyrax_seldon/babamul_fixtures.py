"""Realistic Babamul LSST alerts for tests.

``data/babamul_lsst_schema.json`` is the Avro schema Babamul publishes for LSST alerts
(``https://babamul.caltech.edu/api/babamul/surveys/lsst/schemas``, generated by BOOM's
``BabamulLsstAlert``). :func:`make_alert` fills every field the schema requires with a
placeholder and sets the photometry under test; :func:`encode_alert` writes it as Babamul
does, one Avro object container file per Kafka message.
"""

import io
import json
from pathlib import Path

import fastavro
import numpy as np

SCHEMA = json.loads((Path(__file__).parent / "data" / "babamul_lsst_schema.json").read_text())
PARSED_SCHEMA = fastavro.parse_schema(SCHEMA)

LSST_BANDS = ["u", "g", "r", "i", "z", "y"]
MJD_OFFSET = 2400000.5


def _placeholder(schema, named):
    """Return a minimal value valid for ``schema``: null where allowed, zero, empty."""
    if isinstance(schema, str):
        if schema in named:
            return _placeholder(named[schema], named)
        return {"null": None, "boolean": False, "string": "", "bytes": b"", "int": 0, "long": 0}.get(
            schema, 0.0
        )
    if isinstance(schema, list):
        return None if "null" in schema else _placeholder(schema[0], named)
    kind = schema["type"]
    if "name" in schema and kind in ("record", "enum", "fixed"):
        named[schema["name"]] = schema
    if kind == "record":
        return {field["name"]: _placeholder(field["type"], named) for field in schema["fields"]}
    if kind == "enum":
        return schema["symbols"][0]
    if kind == "array":
        _placeholder(schema["items"], named)  # register any named types defined inside
        return []
    if kind == "map":
        return {}
    return _placeholder(kind, named)


def _named_types(schema, named):
    """Collect every named type in ``schema`` so placeholders can resolve references."""
    if isinstance(schema, list):
        for item in schema:
            _named_types(item, named)
    elif isinstance(schema, dict):
        if schema.get("type") in ("record", "enum", "fixed") and "name" in schema:
            named[schema["name"]] = schema
        for field in schema.get("fields", []):
            _named_types(field["type"], named)
        for key in ("items", "values"):
            if key in schema:
                _named_types(schema[key], named)


NAMED_TYPES: dict = {}
_named_types(SCHEMA, NAMED_TYPES)


def placeholder(type_name: str) -> dict:
    """Return a placeholder value for one of the schema's named types."""
    return _placeholder(NAMED_TYPES[type_name], dict(NAMED_TYPES))


def detection(jd, band, flux, flux_err):
    """A ``prv_candidates`` entry (``AlertPhotometry``)."""
    return {"jd": jd, "psfFlux": flux, "psfFluxErr": flux_err, "band": band, "ra": 150.1, "dec": 2.2}


def forced(jd, band, flux, flux_err):
    """An ``fp_hists`` entry (``ForcedPhotometry``); ``flux`` may be ``None``."""
    return {"jd": jd, "psfFlux": flux, "psfFluxErr": flux_err, "band": band}


def make_alert(candid, object_id, prv_candidates, fp_hists, alert_jd, alert_band):
    """Return a complete Babamul LSST alert dict with the given photometry."""
    alert = placeholder("BabamulLsstAlert")
    alert["candid"] = candid
    alert["objectId"] = object_id
    candidate = alert["candidate"]
    current = next(p for p in prv_candidates if p["jd"] == alert_jd and p["band"] == alert_band)
    candidate.update(
        diaSourceId=candid,
        objectId=object_id,
        jd=alert_jd,
        midpointMjdTai=alert_jd - MJD_OFFSET,
        band=alert_band,
        psfFlux=current["psfFlux"],
        psfFluxErr=current["psfFluxErr"],
        ra=150.1,
        dec=2.2,
    )
    alert["prv_candidates"] = prv_candidates
    alert["fp_hists"] = fp_hists
    return alert


def make_light_curve_alert(rng, candid, object_id, n_visits=80, n_null=3, n_future=2, empty_forced=False):
    """A transient's alert with history in all six bands.

    Every visit has forced photometry; visits where the source is bright are also DIA
    detections (so their forced point is a duplicate). ``n_null`` forced points have a null
    flux, and ``n_future`` visits come after the alert, in both histories, as Babamul's
    accumulated object history can contain.
    """
    jd0 = 2461000.5
    jd = jd0 + np.cumsum(rng.uniform(0.5, 3.0, n_visits + n_future))
    bands = [LSST_BANDS[i % 6] for i in range(n_visits + n_future)]
    peak = jd[n_visits // 2]
    flux_err = rng.uniform(150.0, 400.0, len(jd))
    flux = 40000.0 * np.exp(-0.5 * ((jd - peak) / 15.0) ** 2) + rng.normal(0.0, 1.0, len(jd)) * flux_err

    detected = flux > 5 * flux_err
    detected[n_visits - 1] = True  # the alert's own detection
    alert_jd = float(jd[n_visits - 1])

    prv_candidates = [
        detection(float(jd[i]), bands[i], float(flux[i]), float(flux_err[i]))
        for i in range(len(jd))
        if detected[i]
    ]
    fp_hists = (
        []
        if empty_forced
        else [forced(float(jd[i]), bands[i], float(flux[i]), float(flux_err[i])) for i in range(len(jd))]
    )
    for i in rng.choice(np.where(~detected[:n_visits])[0], n_null, replace=False) if fp_hists else []:
        fp_hists[i]["psfFlux"] = None

    return make_alert(candid, object_id, prv_candidates, fp_hists, alert_jd, bands[n_visits - 1])


def encode_alert(alert) -> bytes:
    """Encode an alert as Babamul does: an Avro object container file with the schema."""
    buffer = io.BytesIO()
    fastavro.writer(buffer, PARSED_SCHEMA, [alert])
    return buffer.getvalue()


def decode_alert(payload: bytes) -> dict:
    """Decode one Babamul message."""
    return next(fastavro.reader(io.BytesIO(payload)))
